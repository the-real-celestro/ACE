#!/usr/bin/env python3
"""Export public ACE generation/effect facts; never copies DATs or user data."""
import argparse
import hashlib
import json
import math
import sqlite3
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--research', type=Path, required=True)
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[2] / 'Source/ACEClient/Private/Loot/ACELootReference.inl')
args = parser.parse_args()
data = json.loads((args.research / 'weapon-ranges-by-tier.json').read_text())
db = sqlite3.connect(args.research / 'loot-reference.sqlite')
db.row_factory = sqlite3.Row
skills = {r['name']: r['value'] for r in db.execute("select name,value from enum_value where enum_name='Skill'")}
properties = ['Damage', 'DamageVariance', 'WeaponOffense', 'WeaponDefense', 'DamageMod', 'ElementalDamageBonus', 'ElementalDamageMod', 'MeanBaseHit', 'ManaConversionMod']
variants = {v['id']: i for i, v in enumerate(data['variants'])}
groups = {}
for row in data['rows']:
    kind = {'None': 0, 'RawSkill': 2, 'Level': 7}[row['requirement_kind']]
    skill = skills.get(row['wield_skill'], 0) if kind == 2 else 0
    key = (variants[row['variant']], kind, skill, row['wield_requirement'] or 0)
    group = groups.setdefault(key, {})
    for prop in properties:
        stat = row['stats'].get(prop, {'minimum': None})
        if stat['minimum'] is None:
            continue
        lo, hi = stat['minimum'], stat['maximum']
        if prop in group:
            lo, hi = min(lo, group[prop][0]), max(hi, group[prop][1])
        group[prop] = [lo, hi]
out = ['// Generated by Tools/LootQuality/export-reference.py. Public ACE baseline.',
       '// Input: ACE-World v0.9.296; source ' + data['metadata']['source_revision'],
       '// Missing dimensions use {-1,-1}; never interpret them as perfect rolls.']
out += ['static constexpr FLootVariant LootVariants[] = {']
for v in data['variants']:
    family = 1 if v['class'] in ('heavy','light','finesse','twohand') else 2 if v['class']=='missile' else 3 if v['class'] in ('war','void') else 4
    if v['class'] == 'utility': family = 4
    out.append('    {%d,%d,TEXT(%s)},' % (family, v['skill_id'] or 0, json.dumps(v['class_label'] + ' / ' + v['subtype'])))
out += ['};', 'static constexpr FLootTemplate LootTemplates[] = {']
templates = set()
for v in data['variants']:
    for ids in v['templates_by_tier'].values():
        templates.update((wcid, variants[v['id']]) for wcid in ids)
for wcid, variant in sorted(templates): out.append(f'    {{{wcid},{variant}}},')
out += ['};', 'static constexpr FLootCohort LootCohorts[] = {']
for (variant, kind, skill, wield), stats in sorted(groups.items()):
    bounds = ','.join('{%.10g,%.10g}' % tuple(stats.get(p, [-1, -1])) for p in properties)
    out.append('    {%d,%d,%d,%d,{%s}},' % (variant, kind, skill, wield, bounds))
out += ['};']
cantrips = {r['spell_id']: dict(r) for r in db.execute('select * from decoded_cantrip_effect')}
legends = {r['family']: r['stat_Mod_Val'] for r in cantrips.values() if r['rank'] == 4}
families = {name: i + 1 for i, name in enumerate(sorted({r['family'] for r in cantrips.values()}))}
out += ['static constexpr FLootSpell LootSpells[] = {']
count = 0
for row in db.execute('select id,stat_Mod_Type,stat_Mod_Key,stat_Mod_Val from world_spell order by id'):
    if row['stat_Mod_Type'] is None or row['stat_Mod_Key'] is None or row['stat_Mod_Val'] is None:
        continue
    if not math.isfinite(row['stat_Mod_Val']): continue
    ct = cantrips.get(row['id'], {})
    out.append('    {%d,%d,%d,%.10g,%d,%d,%.10g},' % (row['id'], row['stat_Mod_Type'], row['stat_Mod_Key'], row['stat_Mod_Val'], families.get(ct.get('family'), 0), ct.get('rank', 0), legends.get(ct.get('family'), 0)))
    count += 1
out += ['};', '']
# Armor family selection mirrors GetMutationScript_ArmorLevel. Society armor
# preserves template wield gates and is deliberately excluded from this baseline.
wcids = {r['name']: r['value'] for r in db.execute("select name,value from enum_value where enum_name='WeenieClassName'")}
armor_templates = {}
for table in db.execute("select id,declaration from chance_table where source_path like '%/ArmorWcids.cs'"):
    name = table['declaration']
    if any(s in name for s in ['CelestialHand','EldrytchWeb','RadiantBlood']): continue
    category = 1 if ' CovenantWcids ' in name else 2 if ' OlthoiWcids ' in name else 0
    for entry in db.execute('select result_expression from chance_entry where table_id=?',(table['id'],)):
        wcid = wcids.get(entry[0].split('.')[-1])
        if not wcid: continue
        ints = dict(db.execute('select type,value from world_weenie_properties_int where object_Id=?',(wcid,)))
        coverage, shield = ints.get(4,0), (ints.get(9,0)&0x200000)!=0
        family = (4 if shield else 3) if category==1 else (6 if shield else 5) if category==2 else 2 if shield else 1 if coverage&0x1c000 else 0
        floats = dict(db.execute('select type,value from world_weenie_properties_float where object_Id=?',(wcid,)))
        dids = dict(db.execute('select type,value from world_weenie_properties_d_i_d where object_Id=?',(wcid,)))
        # MutateFilter is a DID, not the MutateFilter flags themselves.
        mutates = 15 if dids.get(36,0) in (0x0e000012,0x0e000013) else 0
        armor_templates[wcid] = (family, [floats.get(k,1.) for k in [16,17,18,19]], mutates)
out += ['static constexpr FLootArmorTemplate LootArmorTemplates[] = {']
for wcid,(family,elements,mutates) in sorted(armor_templates.items()):
    out.append('    {%d,%d,{%s},%d},' % (wcid,family,','.join('%.8g'%v for v in elements),mutates))
out += ['};']
armor_scripts=['armor_level_non_extremity','armor_level_extremity','shield_level','covenant_armor','covenant_shield','olthoi_armor','olthoi_shield']
armor_groups={}
for index,script in enumerate(armor_scripts):
    for row in db.execute("select tier,properties_json from generation_case where script_path like ? and projection in ('joint','core')",('%/'+script+'.txt',)):
        p=json.loads(row['properties_json']);al=p.get('ArmorLevel')
        if not isinstance(al,dict) or 'low' not in al or not isinstance(al['low'],(float,int)): continue
        kind={'Level':7,'RawSkill':2}.get(p.get('WieldRequirements'),0)
        skill=skills.get(p.get('WieldSkillType'),0) if kind==2 else 0
        wield=p.get('WieldDifficulty',0)
        level=p.get('WieldDifficulty2',0) if p.get('WieldRequirements2')=='Level' else 0
        keys=[(index,kind,skill,wield,level)]
        if row['tier']==8:
            if kind==7 and wield==150: keys.append((index,kind,skill,180,level))
            elif kind==2 and level==150:keys.append((index,kind,skill,wield,180))
        for key in keys:
            old=armor_groups.get(key,[al['low'],al['high']]);armor_groups[key]=[min(old[0],al['low']),max(old[1],al['high'])]
out += ['static constexpr FLootArmorCohort LootArmorCohorts[] = {']
for key,bounds in sorted(armor_groups.items()):out.append('    {%s,{%g,%g}},'%(','.join(str(k) for k in key),*bounds))
out += ['};','']
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(out))
manifest = {'source_revision': data['metadata']['source_revision'], 'world_release': data['metadata']['world_release'],
    'world_sha256': data['metadata']['world_sha256'], 'weapon_variants': len(variants), 'template_memberships': len(templates),
    'cohorts_across_eligible_tiers': len(groups), 'native_spell_effects': count, 'cantrip_effects': len(cantrips),
    'armor_templates':len(armor_templates),'armor_cohorts':len(armor_groups),
    'output_sha256': hashlib.sha256(args.output.read_bytes()).hexdigest(),
    'scope': 'Ordinary public ACE generation, quality modifier zero; custom/fixed items or unsupported dimensions must remain unrated.'}
args.output.with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(json.dumps(manifest, indent=2))
