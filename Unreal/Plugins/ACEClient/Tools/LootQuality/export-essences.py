#!/usr/bin/env python3
"""Export public ACE loot-essence identities and use brackets; no player data."""
import argparse
import json
import re
import sqlite3
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('database', type=Path)
parser.add_argument('--research', type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[5]
client = Path(__file__).resolve().parents[2]
source = root / 'Source/ACE.Server'
table = source / 'Factories/Tables/Wcids/PetDeviceWcids.cs'
ids = sorted(set(map(int, re.findall(r'WeenieClassName\.ace(\d+)_', table.read_text()))))
db = sqlite3.connect(f'file:{args.database}?mode=ro', uri=True)
def props(wcid):
    return dict(db.execute('SELECT type,value FROM world_weenie_properties_int WHERE object_Id=?', (wcid,)))
rows = []
for wcid in ids:
    p = props(wcid)
    assert p[366] == 54
    pet = props(p[266])
    # The old server mapping dictionary is stale for some skeletons/wasps.
    # Actual summon selection uses the world's PetClass, not that dictionary.
    types = {r[0] for r in db.execute(
        'SELECT d_Type FROM world_weenie_properties_body_part WHERE object_Id=?', (p[266],)) if r[0]}
    assert len(types) == 1
    assert pet[25] in (50, 80, 100, 125, 150, 180, 200)
    row = [wcid, p[266], pet[25], p[367], p.get(368, 0), p[369], p[362], types.pop()]
    rows.append(row)
out = client / 'Source/ACEClient/Private/Loot/ACEEssenceReference.inl'
out.write_text('// Generated by Tools/LootQuality/export-essences.py from public ACE world v0.9.296.\n'
    '// WCID, pet WCID, pet level, current Summoning, specialized skill, user level, mastery, damage type.\n'
    'static constexpr FLootEssenceTemplate LootEssences[] = {\n'
    + ''.join('    {' + ','.join(map(str, r)) + '},\n' for r in rows) + '};\n')
if args.research:
    args.research.write_text(json.dumps(dict(
        source='Public ACE loot generator and world v0.9.296',
        formula='Six independent ratings; 50% absent (0); otherwise inclusive d10 + optional inclusive d10.',
        second_die_chance='0.4 + 0.02 * loot_tier',
        rating_properties=[370,371,372,373,374,375], minimum_each=0, maximum_each=20,
        total_minimum=0, total_maximum=120,
        quality='100 * sum(six ratings) / 120; combination quality, not drop percentile.',
        excluded='Workmanship, remaining charges, player bonuses and use eligibility do not change intrinsic roll quality.',
        templates=rows), indent=2) + '\n')
print(f'Exported {len(rows)} essence templates across seven pet levels.')
